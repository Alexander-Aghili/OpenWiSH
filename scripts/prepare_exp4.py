"""Build assets/exp4/ and tasks/exp4/task.toml from the authors' Experiment 4 logs (assets/lm_understand-logs).

- assets/exp4/prompts/repair.txt: the authors' prompt, verbatim.
- assets/exp4/base_shown/<name>.npy: the actor exactly as shown in that prompt (each tensor is printed as integers
  times one scale; edits are applied to these rounded weights, as in the authors' harness). float32.
- tasks/exp4/task.toml: the task spec (one reply, no tools, edit language, scored on 1,024 test episodes).

Plain Python (no numpy). usage: python3 scripts/prepare_exp4.py"""
import os
import re
import shutil
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RUN = os.path.join(ROOT, "assets", "lm_understand-logs", "exp4_fix_car", "runs", "oneshot_repair")
PROMPT = os.path.join(RUN, "reply", "prompt.txt")
A = os.path.join(ROOT, "assets", "exp4")
T = os.path.join(ROOT, "tasks", "exp4")
HEADER = ("# Generated by scripts/prepare_exp4.py from github.com/RikiyaT/lm_understand-logs (CC BY 4.0).\n")

NAMES = ["embed.W", "embed.b"] + [f"actor{k}.{p}" for k in range(5) for p in ("W", "b")] + ["actor_head.W", "actor_head.b"]
HEAD = re.compile(r"^(\S+) \((\d+)(?: x (\d+))?\), scale (\S+):")


def parse_prompt(text):
    """{name: (shape, [int, ...], scale_str)} for every tensor in the prompt's weights section."""
    lines = text.splitlines()
    start = next(i for i, l in enumerate(lines) if l.startswith("THE WEIGHTS"))
    out, i = {}, start + 1
    while i < len(lines):
        m = HEAD.match(lines[i])
        if not m:
            i += 1
            continue
        name, r, c, scale = m.group(1), int(m.group(2)), m.group(3), m.group(4)
        i += 1
        if c is None:  # vector: the integers follow on one line
            ints = [int(x) for x in lines[i].split()]
            shape = (r,)
            i += 1
        else:  # matrix: one line per row, "i: ints"
            c = int(c)
            ints = []
            for row in range(r):
                idx, vals = lines[i].split(":", 1)
                assert int(idx) == row, f"{name}: expected row {row}, got {idx!r}"
                vals = [int(x) for x in vals.split()]
                assert len(vals) == c, f"{name} row {row}: {len(vals)} values, expected {c}"
                ints += vals
                i += 1
            shape = (r, c)
        n = 1
        for s in shape:
            n *= s
        assert len(ints) == n, f"{name}: {len(ints)} values, expected {n}"
        out[name] = (shape, ints, scale)
    assert sorted(out) == sorted(NAMES), f"tensors in prompt: {sorted(out)}"
    return out


def npy_f32(shape, values):
    h = "{'descr': '<f4', 'fortran_order': False, 'shape': (%s), }" % (", ".join(map(str, shape)) + ("," if len(shape) == 1 else ""))
    while (10 + len(h) + 1) % 64:
        h += " "
    h += "\n"
    return b"\x93NUMPY\x01\x00" + struct.pack("<H", len(h)) + h.encode() + struct.pack(f"<{len(values)}f", *values)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


def main():
    text = open(PROMPT).read()
    tensors = parse_prompt(text)
    os.makedirs(os.path.join(A, "prompts"), exist_ok=True)
    shutil.copyfile(PROMPT, os.path.join(A, "prompts", "repair.txt"))
    d = os.path.join(A, "base_shown")
    os.makedirs(d, exist_ok=True)
    total = 0
    for name, (shape, ints, scale) in tensors.items():
        s = float(scale)
        # value = integer x scale, computed in double and stored as float32 (the harness's tensor type)
        open(os.path.join(d, name + ".npy"), "wb").write(npy_f32(shape, [k * s for k in ints]))
        total += len(ints)
    assert total == 171_664, total
    write(os.path.join(T, "task.toml"), HEADER + '''id = "exp4-repair"
description = "Experiment 4: fix the failing Kinetix car network (l/h2_car_ramp) by editing its weights, in one reply, with no tools."
prompt = "../../assets/exp4/prompts/repair.txt"

[network]
base = "../../assets/exp4/base_shown"

[edits]
language = true

[editor]
effort = "high"

[finish]
max_turns = 1

[score]
command = ["{root}/assets/venvs/kinetix/bin/python", "-I", "{root}/python/adapters/kinetix_eval.py", "--episodes", "1024", "--stream", "test"]

[access]
weights = "prompt"
shown = ["success statistics of the failing network over 256 sampled episodes", "one sampled failure episode, every 16 steps"]
''')
    print(f"prepared exp4: {len(tensors)} tensors, {total} entries -> {d}; prompt -> {A}/prompts/repair.txt; "
          f"task -> {T}/task.toml", file=sys.stderr)


if __name__ == "__main__":
    main()

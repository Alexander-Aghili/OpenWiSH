#!/usr/bin/env python3
"""Contamination variants of Experiments 1 and 2: the same networks with their hidden units permuted.

Permuting hidden units leaves the function unchanged but changes every weight matrix's layout, so a model that
recognises the published weights (or their prompts) from training data no longer sees them. The numbers are the
published numbers, moved: the permuted prompt is the published prompt with weight rows and columns reordered, and
every other line is unchanged. Answers and scorers are the originals.

usage: python3 scripts/prepare_contamination.py [--seed 20261103]
writes assets/exp{1,2}-perm/prompts/<id>.txt and tasks/exp{1,2}-perm/<id>.toml
"""
import argparse
import glob
import os
import random
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = re.compile(r"^(W[123]|b[123]) \(.*\), shape (\d+)(?: x (\d+))?:")


def parse_blocks(text):
    """name -> {"shape": (rows, cols) or (n,), "lines": [line indices], "rows": [token lists per line]}"""
    lines = text.splitlines()
    blocks, i = {}, 0
    while i < len(lines):
        m = HEADER.match(lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1)
        shape = (int(m.group(2)), int(m.group(3))) if m.group(3) else (int(m.group(2)),)
        need = shape[0] * (shape[1] if len(shape) == 2 else 1)
        got, idx, rows, j = 0, [], [], i + 1
        while got < need:
            toks = lines[j].split()
            if toks:
                idx.append(j)
                rows.append(toks)
                got += len(toks)
            j += 1
        if got != need:
            raise ValueError(f"{name}: {got} values, expected {need}")
        if len(shape) == 2 and any(len(r) != shape[1] for r in rows):
            raise ValueError(f"{name}: expected one line of {shape[1]} values per row")
        blocks[name] = {"shape": shape, "lines": idx, "rows": rows}
        i = j
    missing = {"W1", "b1", "W2", "b2", "W3", "b3"} - set(blocks)
    if missing:
        raise ValueError(f"weight blocks not found: {sorted(missing)}")
    return blocks


def _vec_permute(rows, perm):
    """Reorder a vector spread over lines, keeping the per-line counts."""
    flat = [v for r in rows for v in r]
    flat = [flat[p] for p in perm]
    out, k = [], 0
    for r in rows:
        out.append(flat[k:k + len(r)])
        k += len(r)
    return out


def permute_prompt(text, seed):
    """The prompt with hidden layers 1 and 2 permuted (new unit j = old unit perm[j]). Returns (text, perms)."""
    b = parse_blocks(text)
    h1, h2 = b["W1"]["shape"][1], b["W2"]["shape"][1]
    rng = random.Random(seed)
    p1, p2 = list(range(h1)), list(range(h2))
    while p1 == sorted(p1):
        rng.shuffle(p1)
    while p2 == sorted(p2):
        rng.shuffle(p2)
    new = {
        "W1": [[r[p] for p in p1] for r in b["W1"]["rows"]],
        "b1": _vec_permute(b["b1"]["rows"], p1),
        "W2": [[b["W2"]["rows"][p][q] for q in p2] for p in p1],
        "b2": _vec_permute(b["b2"]["rows"], p2),
        "W3": [b["W3"]["rows"][p] for p in p2],
        "b3": b["b3"]["rows"],
    }
    lines = text.splitlines()
    for name, rows in new.items():
        for li, toks in zip(b[name]["lines"], rows):
            lines[li] = " ".join(toks)
    out = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    return out, {"h1": p1, "h2": p2}


SPEC = """# Generated by scripts/prepare_contamination.py: the published network with its hidden units permuted (seed {seed}).
id = "{exp}-perm-{nid}"
description = "{desc} Contamination variant: hidden units permuted, same function, same answer."
prompt = "../../assets/{exp}-perm/prompts/{nid}.txt"
hidden = ["../../assets/{exp}/answer_key.json"]

[editor]
effort = "high"

[finish]
max_turns = 1

[score]
command = ["python3", "-I", "{{root}}/tasks/{exp}/score.py", "{{root}}/assets/{exp}/answer_key.json", "{nid}"]

[access]
weights = "prompt"
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=20261103)
    a = ap.parse_args()
    for exp, desc in (("exp1", "Experiment 1: which game was this network trained on?"),
                      ("exp2", "Experiment 2: what does this diffusion model generate?")):
        for path in sorted(glob.glob(os.path.join(ROOT, "assets", exp, "prompts", "*.txt"))):
            nid = os.path.basename(path)[:-4]
            text = open(path).read()
            new, _ = permute_prompt(text, a.seed)
            pdir = os.path.join(ROOT, "assets", f"{exp}-perm", "prompts")
            tdir = os.path.join(ROOT, "tasks", f"{exp}-perm")
            os.makedirs(pdir, exist_ok=True)
            os.makedirs(tdir, exist_ok=True)
            open(os.path.join(pdir, nid + ".txt"), "w").write(new)
            open(os.path.join(tdir, nid + ".toml"), "w").write(SPEC.format(seed=a.seed, exp=exp, nid=nid, desc=desc))
            print(f"{exp}-perm/{nid}")


if __name__ == "__main__":
    main()

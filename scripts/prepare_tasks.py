def zero_mlp(d, sizes):
    """A directory of zero tensors W1, b1, ... for an MLP with the given layer sizes (written without numpy)."""
    import struct
    os.makedirs(d, exist_ok=True)

    def npy(shape, n):
        h = "{'descr': '<f4', 'fortran_order': False, 'shape': (%s), }" % (", ".join(map(str, shape)) + ("," if len(shape) == 1 else ""))
        while (10 + len(h) + 1) % 64:
            h += " "
        h += "\n"
        return b"\x93NUMPY\x01\x00" + struct.pack("<H", len(h)) + h.encode() + b"\x00" * (4 * n)

    for i in range(len(sizes) - 1):
        open(f"{d}/W{i + 1}.npy", "wb").write(npy((sizes[i], sizes[i + 1]), sizes[i] * sizes[i + 1]))
        open(f"{d}/b{i + 1}.npy", "wb").write(npy((sizes[i + 1],), sizes[i + 1]))



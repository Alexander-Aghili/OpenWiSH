def exp6():
    import struct
    d = f"{A}/exp6/zero_net"
    os.makedirs(d, exist_ok=True)

    def npy(shape):
        h = "{'descr': '<f4', 'fortran_order': False, 'shape': (%s), }" % (", ".join(map(str, shape)) + ("," if len(shape) == 1 else ""))
        while (10 + len(h) + 1) % 64:
            h += " "
        h += "\n"
        n = 1
        for x in shape:
            n *= x
        return b"\x93NUMPY\x01\x00" + struct.pack("<H", len(h)) + h.encode() + b"\x00" * (4 * n)

    for k in range(1, 7):
        open(f"{d}/L{k}.W.npy", "wb").write(npy((243 if k == 1 else 512, 512)))
        open(f"{d}/L{k}.b.npy", "wb").write(npy((512,)))
    open(f"{d}/out.W.npy", "wb").write(npy((512, 82)))
    open(f"{d}/out.b.npy", "wb").write(npy((82,)))
    opp = "{root}/assets/exp6/opponents"
    # the authors' released same-size PPO networks: head-to-head opponents comparable with the published numbers

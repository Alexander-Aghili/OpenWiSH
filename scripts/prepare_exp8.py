def bf16_to_f32(raw):
    return (raw.astype(np.uint32) << 16).view(np.float32)


def text_checkpoint():
    out = f"{A}/qwen35-text"
    if os.path.exists(f"{out}/model.safetensors"):
        return
    os.makedirs(out, exist_ok=True)
    src = f"{A}/qwen35-hf/model.safetensors-00001-of-00001.safetensors"
    # safetensors.numpy cannot hold bf16 directly: read the raw file and keep bf16 bits as they are
    import struct
    with open(src, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        header = json.loads(f.read(n))
        header.pop("__metadata__", None)
        body_off = 8 + n
    keep = sorted(k for k in header if k.startswith("model.language_model."))
    raw = np.memmap(src, dtype=np.uint8, mode="r", offset=body_off)
    hdr, chunks, off = {}, [], 0
    for k in keep:
        a, b = header[k]["data_offsets"]
        buf = bytes(raw[a:b])
        hdr[k] = {"dtype": header[k]["dtype"], "shape": header[k]["shape"], "data_offsets": [off, off + len(buf)]}
        chunks.append(buf)
        off += len(buf)
    hdr["__metadata__"] = {"format": "pt"}
    h = json.dumps(hdr, separators=(",", ":")).encode()
    h += b" " * (-len(h) % 8)
    with open(f"{out}/model.safetensors", "wb") as f:
        f.write(struct.pack("<Q", len(h)))
        f.write(h)
        for c in chunks:
            f.write(c)
    shutil.copyfile(f"{LOGS}/base_model/Qwen3.5-0.8B-text/config.json", f"{out}/config.json")
    for name in ("tokenizer.json", "tokenizer_config.json", "chat_template.jinja", "generation_config.json"):
        src_f = f"{LOGS}/base_model/Qwen3.5-0.8B-text/{name}"
        if not os.path.exists(src_f):
            src_f = f"{A}/qwen35-hf/{name}"
        if os.path.exists(src_f):
            shutil.copyfile(src_f, f"{out}/{name}")
    print("text checkpoint:", len(keep), "tensors")


def base_net():
    """The base network as float32 .npy files (one per tensor) for the edit gate and the editor's load()."""
    out = f"{A}/base_net"
    if os.path.exists(f"{out}/.done"):
        return
    os.makedirs(out, exist_ok=True)
    import struct
    src = f"{A}/qwen35-text/model.safetensors"
    with open(src, "rb") as f:
        n = struct.unpack("<Q", f.read(8))[0]
        header = json.loads(f.read(n))
    header.pop("__metadata__", None)
    raw = np.memmap(src, dtype=np.uint8, mode="r", offset=8 + n)
    for k, v in header.items():
        a, b = v["data_offsets"]
        buf = np.frombuffer(bytes(raw[a:b]), dtype=np.uint16 if v["dtype"] == "BF16" else np.float32)
        x = bf16_to_f32(buf) if v["dtype"] == "BF16" else buf
        np.save(f"{out}/{k.replace('/', '__')}.npy", x.reshape(v["shape"]).astype(np.float32))
    open(f"{out}/.done", "w").write("ok")
    print("base_net:", len(header), "tensors")


def eval_sets():
    """Hidden evaluation sets (never mounted): MATH-500 and GSM8K test."""
    d = f"{A}/eval"
    os.makedirs(d, exist_ok=True)
    urls = {
        "math500.jsonl": "https://huggingface.co/datasets/HuggingFaceH4/MATH-500/resolve/main/test.jsonl",
        "gsm8k_test.jsonl": "https://raw.githubusercontent.com/openai/grade-school-math/master/grade_school_math/data/test.jsonl",
    }
    for name, url in urls.items():
        p = f"{d}/{name}"
        if not os.path.exists(p):
            urllib.request.urlretrieve(url, p)
    print("eval sets ready")


